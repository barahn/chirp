#!/usr/bin/env bash
#
# Refreshes the machine-checkable parts of HANDOFF.md from the repository
# itself, so the handoff prompt a continuation agent reads is never describing
# a tree that has moved on without it.
#
# HANDOFF.md is mostly prose -- roadmap, constraints, working agreement -- and
# that prose is hand-written and left alone. What rots is the factual snapshot:
# the file layout, the module and its dependencies, the packages, whether the
# tests pass. Those live between generated markers and are rewritten here.
#
# The snapshot is a function of the tree alone. CI regenerates it and fails if
# the committed copy differs, the way THIRD_PARTY_NOTICES.md is checked, so it
# must come out identical on a pull request's head and on the merge that lands
# it. That rules out anything read from history -- the commit log, a commit
# count, a branch name -- because merging changes all three and not the tree.
# For history, run git log.
#
# The markers are:
#
#   <!-- BEGIN GENERATED: <name> -->
#   <!-- END GENERATED: <name> -->
#
# Text outside them is preserved byte for byte. A marker that is missing is an
# error rather than a silent no-op: a renamed section must be a deliberate edit
# to this script, not a block that quietly stops updating.
#
# Usage: scripts/gen-handoff.sh [handoff-file]
#
# SPDX-License-Identifier: AGPL-3.0-only
# Copyright (C) 2026 Fabrintek Engenharia Digital Ltda

set -euo pipefail

OUT="${1:-HANDOFF.md}"

if [ ! -f "$OUT" ]; then
	echo "error: $OUT does not exist" >&2
	exit 1
fi

REPO_ROOT="$(git rev-parse --show-toplevel)"
cd "$REPO_ROOT"

# replace_block <name> <file-with-new-content>
#
# Swaps everything between the named markers for the given content. Refuses to
# run if either marker is absent or duplicated.
replace_block() {
	local name="$1" body_file="$2"
	local begin="<!-- BEGIN GENERATED: ${name} -->"
	local end="<!-- END GENERATED: ${name} -->"

	local n_begin n_end
	n_begin="$(grep -cF "$begin" "$OUT" || true)"
	n_end="$(grep -cF "$end" "$OUT" || true)"
	if [ "$n_begin" != "1" ] || [ "$n_end" != "1" ]; then
		echo "error: expected exactly one '${name}' marker pair in $OUT (found ${n_begin} begin, ${n_end} end)" >&2
		exit 1
	fi

	awk -v begin="$begin" -v end="$end" -v body="$body_file" '
		$0 == begin { print; while ((getline line < body) > 0) print line; close(body); skip = 1; next }
		$0 == end   { print; skip = 0; next }
		!skip       { print }
	' "$OUT" > "${OUT}.tmp"
	mv "${OUT}.tmp" "$OUT"
}

TMPDIR_WORK="$(mktemp -d)"
trap 'rm -rf "$TMPDIR_WORK"' EXIT

# --- snapshot: commit log, layout, module, test state ------------------------

SNAPSHOT="$TMPDIR_WORK/snapshot.md"

# Direct requirements, straight out of go.mod: no module cache, no network, so
# this works in a CI job that has not run `go mod download` yet.
list_direct_deps() {
	awk '
		/^require \(/           { in_block = 1; next }
		in_block && /^\)/       { in_block = 0; next }
		/\/\/ indirect/        { next }
		in_block && NF >= 2     { printf "- `%s` %s\n", $1, $2 }
		!in_block && /^require / && NF >= 3 { printf "- `%s` %s\n", $2, $3 }
	' go.mod
}

{
	printf '_Generated by `scripts/gen-handoff.sh` -- do not edit by hand._\n\n'

	printf '**Module** `%s`, targeting Go `%s`.\n\n' \
		"$(awk '/^module /{print $2; exit}' go.mod)" \
		"$(awk '/^go /{print $2; exit}' go.mod)"

	printf '**Direct dependencies:**\n\n'
	DEPS="$(list_direct_deps)"
	if [ -n "$DEPS" ]; then
		printf '%s\n\n' "$DEPS"
	else
		printf -- '- none\n\n'
	fi

	printf '**Tracked files:**\n\n```\n'
	git ls-files
	printf '```\n\n'

	printf '**Packages:**\n\n```\n'
	go list ./... 2>/dev/null || printf '(go list unavailable in this environment)\n'
	printf '```\n\n'

	# Recorded rather than enforced. This script documents the tree; it is not a
	# second test gate, and a red suite here must not block the refresh -- an
	# out-of-date handoff is worse than one that says the tests are failing.
	#
	# Per-package durations and the "(cached)" marker are stripped: they change
	# between runs without the tree changing, and the workflow commits whatever
	# this script produces. Leaving them in would mean a churn commit on every
	# push to main.
	printf '**Test state** at this refresh:\n\n```\n'
	if TEST_OUT="$(go test -count=1 ./... 2>&1)"; then
		printf '%s\n' "$TEST_OUT" | sed -E 's/[[:space:]]+(\(cached\)|[0-9]+\.[0-9]+s)$//' | tail -20
	else
		printf 'FAILING:\n%s\n' "$TEST_OUT" | sed -E 's/[[:space:]]+(\(cached\)|[0-9]+\.[0-9]+s)$//' | tail -25
	fi
	printf '```\n'
} > "$SNAPSHOT"

replace_block "snapshot" "$SNAPSHOT"

echo "✓ refreshed generated sections of $OUT"
